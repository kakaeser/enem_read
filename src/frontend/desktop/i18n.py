_active_lang: str = "pt_BR"


def set_language(lang: str) -> None:
    global _active_lang
    if lang not in LANGUAGES:
        raise ValueError(f"Unsupported language: {lang}")
    _active_lang = lang


def get_language() -> str:
    return _active_lang


def t(key: str) -> str:
    return STRINGS.get(_active_lang, {}).get(key, key)
